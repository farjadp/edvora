/**
 * Access-tester cast (board E-041, `.claude/agents/access-tester.md`): one test user per access level in the `demo`
 * academy, plus the records the access matrix needs (two leads with different owners, orders for IDOR checks, a second
 * course for scope checks, an archived role, and a `demo2` academy for cross-academy checks).
 *
 *   pnpm --filter @edvora/web seed:access
 *
 * Idempotent: users are found by email, memberships by their note, records by natural keys.
 * Safety: refuses when NODE_ENV=production unless ALLOW_DEMO_SEED=true, never touches the `iba` academy, and
 * writes passwords only to apps/web/.env (git-ignored) as ACCESS_<KEY>_PASSWORD. Passwords are never printed.
 * Needs `pnpm seed` first (demo academy, role templates, super admin).
 */
import { randomBytes } from 'node:crypto'
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { getPayload, type Payload, type Where } from 'payload'
import config from '../payload.config'

const TENANT = 'demo'
const OTHER_TENANT = 'demo2'
const ENV_FILE = join(process.cwd(), '.env')
const DAY = 24 * 60 * 60 * 1000

export type AccessKey =
  | 'academy-admin'
  | 'advisor'
  | 'instructor'
  | 'finance'
  | 'support'
  | 'content-editor'
  | 'instructor-scoped'
  | 'advisor-own'
  | 'multi-role'
  | 'two-academies'
  | 'expired'
  | 'suspended'
  | 'archived-role'
  | 'student'
  | 'student-other'
  | 'student-unpaid'

type Spec = {
  key: AccessKey
  name: string
  /** Role keys in the demo academy (one membership). Empty = no membership (students). */
  roles: string[]
  phone?: string
  status?: 'active' | 'suspended'
  student?: boolean
  scope?: 'demo-program' | null
  ownRecordsOnly?: boolean
  expired?: boolean
}

/** Phones from the seed's reserved fake range (0912999xxxx); 099902xx is this script's block. */
const CAST: readonly Spec[] = [
  { key: 'academy-admin', name: 'تست دسترسی مدیر آکادمی', roles: ['academy-admin'] },
  { key: 'advisor', name: 'تست دسترسی مشاور', roles: ['advisor'] },
  { key: 'instructor', name: 'تست دسترسی مدرس', roles: ['instructor'] },
  { key: 'finance', name: 'تست دسترسی مالی', roles: ['finance'] },
  { key: 'support', name: 'تست دسترسی پشتیبانی', roles: ['support'] },
  { key: 'content-editor', name: 'تست دسترسی محتوا', roles: ['content-editor'] },
  { key: 'instructor-scoped', name: 'تست دسترسی مدرس محدود', roles: ['instructor'], scope: 'demo-program' },
  { key: 'advisor-own', name: 'تست دسترسی مشاور فقط خودش', roles: ['advisor'], ownRecordsOnly: true },
  { key: 'multi-role', name: 'تست دسترسی دو نقش', roles: ['advisor', 'content-editor'] },
  { key: 'two-academies', name: 'تست دسترسی دو آکادمی', roles: ['academy-admin'] },
  { key: 'expired', name: 'تست دسترسی منقضی', roles: ['academy-admin'], expired: true },
  { key: 'suspended', name: 'تست دسترسی معلق', roles: ['academy-admin'], status: 'suspended' },
  { key: 'archived-role', name: 'تست دسترسی نقش بایگانی', roles: ['access-archived'] },
  { key: 'student', name: 'تست دسترسی دانشجو', roles: [], student: true, phone: '09129990201' },
  { key: 'student-other', name: 'تست دسترسی دانشجوی دیگر', roles: [], student: true, phone: '09129990202' },
  { key: 'student-unpaid', name: 'تست دسترسی دانشجوی بدهکار', roles: [], student: true, phone: '09129990203' },
]

export const accessEmail = (key: AccessKey) => `access+${key}@edvora.demo`
export const accessPasswordVar = (key: AccessKey) => `ACCESS_${key.toUpperCase().replace(/-/g, '_')}_PASSWORD`

function refuseUnsafe(): void {
  if (process.env.NODE_ENV === 'production' && process.env.ALLOW_DEMO_SEED !== 'true') {
    throw new Error('Refusing to seed access users with NODE_ENV=production (set ALLOW_DEMO_SEED=true for a demo environment)')
  }
  const wanted = process.env.ACCESS_SEED_TENANT ?? TENANT
  if (wanted !== TENANT) throw new Error(`Access users are seeded into "${TENANT}" only (got "${wanted}")`)
}

/** Reads ACCESS_*_PASSWORD from apps/web/.env, generating and appending the missing ones. Values never leave this file. */
function passwords(): Record<string, string> {
  const text = existsSync(ENV_FILE) ? readFileSync(ENV_FILE, 'utf8') : ''
  const current = new Map<string, string>()
  for (const line of text.split('\n')) {
    const m = /^(ACCESS_[A-Z_]+_PASSWORD)=(.+)$/.exec(line.trim())
    if (m) current.set(m[1]!, m[2]!)
  }
  const added: string[] = []
  for (const spec of CAST) {
    const v = accessPasswordVar(spec.key)
    if (!current.has(v)) {
      const pw = `Ax-${randomBytes(18).toString('base64url')}`
      current.set(v, pw)
      added.push(`${v}=${pw}`)
    }
  }
  if (added.length) {
    const header = text.includes('# --- Access tester') ? '' : '\n# --- Access tester (E-041): generated by seed-access-users.ts, never commit ---\n'
    writeFileSync(ENV_FILE, `${text.replace(/\n*$/, '\n')}${header}${added.join('\n')}\n`, { mode: 0o600 })
  }
  return Object.fromEntries(current)
}

async function one<T>(payload: Payload, collection: Parameters<Payload['find']>[0]['collection'], where: Parameters<Payload['find']>[0]['where']): Promise<T | undefined> {
  return (await payload.find({ collection, where, limit: 1, depth: 0, overrideAccess: true })).docs[0] as T | undefined
}

async function upsertBy<T extends { id: number }>(payload: Payload, collection: Parameters<Payload['find']>[0]['collection'], where: Parameters<Payload['find']>[0]['where'], data: Record<string, unknown>): Promise<T> {
  const found = await one<T>(payload, collection, where)
  if (found) return (await payload.update({ collection, id: found.id, data: data as never, overrideAccess: true })) as unknown as T
  return (await payload.create({ collection, data: data as never, overrideAccess: true })) as unknown as T
}

type Ref = { id: number }

async function main(): Promise<void> {
  refuseUnsafe()
  const pw = passwords()
  const payload = await getPayload({ config })

  const demo = await one<Ref & { slug: string }>(payload, 'tenants', { slug: { equals: TENANT } })
  if (!demo) throw new Error('Demo academy not found — run `pnpm seed` first')
  const t = demo.id
  const roleId = async (key: string) => {
    const r = await one<Ref>(payload, 'roles', { and: [{ tenant: { equals: t } }, { key: { equals: key } }] })
    if (!r) throw new Error(`Missing role ${key} in demo — run \`pnpm seed\` first`)
    return r.id
  }

  // Custom role that is archived after it was assigned (memberships cannot pick an archived role). It would grant a lot,
  // but archived roles grant nothing. Un-archived first so a re-run can re-save the membership.
  const archivedRole = await upsertBy<Ref>(payload, 'roles', { and: [{ tenant: { equals: t } }, { key: { equals: 'access-archived' } }] }, {
    tenant: t,
    key: 'access-archived',
    name: 'نقش بایگانی‌شده (تست دسترسی)',
    permissions: ['leads.view.all', 'orders.view', 'users.view', 'users.view_sensitive', 'roles.view'],
    archived: false,
  })

  const course = await one<Ref>(payload, 'courses', { and: [{ tenant: { equals: t } }, { slug: { equals: 'demo-program' } }] })
  if (!course) throw new Error('demo-program not found — run `pnpm seed` first')
  const cohort = await one<Ref>(payload, 'cohorts', { and: [{ tenant: { equals: t } }, { course: { equals: course.id } }] })

  // A second demo course (draft, never public) so scoped instructors have something outside their scope.
  const otherCourse = await upsertBy<Ref>(payload, 'courses', { and: [{ tenant: { equals: t } }, { slug: { equals: 'access-scope-course' } }] }, {
    tenant: t,
    title: 'دورهٔ تست دسترسی (خارج از محدوده)',
    slug: 'access-scope-course',
    kind: 'program',
    status: 'draft',
    price: 10_000_000,
  })
  await upsertBy(payload, 'lessons', { and: [{ course: { equals: otherCourse.id } }, { order: { equals: 1 } }] }, {
    tenant: t,
    course: otherCourse.id,
    title: 'جلسهٔ تست دسترسی',
    order: 1,
  })

  // demo2: a second fake academy for cross-academy checks. Holds one course and one lead; no staff of ours.
  const demo2 = await upsertBy<Ref>(payload, 'tenants', { slug: { equals: OTHER_TENANT } }, {
    name: 'آکادمی تست دوم',
    slug: OTHER_TENANT,
    domains: [{ domain: 'demo2.localhost' }],
  })
  const demo2Course = await upsertBy<Ref>(payload, 'courses', { and: [{ tenant: { equals: demo2.id } }, { slug: { equals: 'demo2-course' } }] }, {
    tenant: demo2.id,
    title: 'دورهٔ آکادمی تست دوم',
    slug: 'demo2-course',
    kind: 'program',
    status: 'draft',
    price: 10_000_000,
  })
  await upsertBy(payload, 'leads', { and: [{ tenant: { equals: demo2.id } }, { phone: { equals: '09129990299' } }] }, {
    tenant: demo2.id,
    name: 'سرنخ آکادمی دوم (تست)',
    phone: '09129990299',
    course: demo2Course.id,
    status: 'new',
  })

  const ids = new Map<AccessKey, number>()
  for (const spec of CAST) {
    const email = accessEmail(spec.key)
    const base = {
      name: spec.name,
      tenants: [{ tenant: t }],
      roles: spec.student ? ['student'] : [],
      status: spec.status ?? 'active',
      password: pw[accessPasswordVar(spec.key)],
      ...(spec.phone ? { phone: spec.phone } : {}),
      ...(spec.student ? { nationalCode: '0000000000', internalNotes: 'یادداشت داخلی تست — نباید به دانشجو نمایش داده شود' } : {}),
    }
    const user = await upsertBy<Ref>(payload, 'users', { email: { equals: email } }, { email, ...base })
    ids.set(spec.key, user.id)

    if (spec.roles.length) {
      const roles = await Promise.all(spec.roles.map(roleId))
      const note = `access-tester:${spec.key}`
      await upsertBy(payload, 'memberships', { note: { equals: note } }, {
        tenant: t,
        user: user.id,
        roles,
        status: 'active',
        expiresAt: spec.expired ? new Date(Date.now() - DAY).toISOString() : null,
        scope: {
          courses: spec.scope ? [course.id] : [],
          cohorts: spec.scope && cohort ? [cohort.id] : [],
          ownRecordsOnly: Boolean(spec.ownRecordsOnly),
        },
        note,
      })
    }
  }

  await payload.update({ collection: 'roles', id: archivedRole.id, data: { archived: true }, overrideAccess: true })

  // Leads: one owned by `advisor`, one by `advisor-own`, one unassigned.
  const leads: { phone: string; name: string; advisor: AccessKey | null }[] = [
    { phone: '09129990211', name: 'سرنخ مشاور (تست دسترسی)', advisor: 'advisor' },
    { phone: '09129990212', name: 'سرنخ مشاور فقط خودش (تست دسترسی)', advisor: 'advisor-own' },
    { phone: '09129990213', name: 'سرنخ بدون مشاور (تست دسترسی)', advisor: null },
  ]
  for (const l of leads) {
    await upsertBy(payload, 'leads', { and: [{ tenant: { equals: t } }, { phone: { equals: l.phone } }] }, {
      tenant: t,
      name: l.name,
      phone: l.phone,
      course: course.id,
      status: 'new',
      advisor: l.advisor ? ids.get(l.advisor) : null,
    })
  }

  // Students: two enrolled with a paid order each (IDOR pair), one with an unpaid instalment and no enrollment.
  const price = 10_000_000
  for (const key of ['student', 'student-other', 'student-unpaid'] as const) {
    const uid = ids.get(key)!
    const unpaid = key === 'student-unpaid'
    const orderWhere: Where = { and: [{ user: { equals: uid } }, { course: { equals: course.id } }] }
    await upsertBy(payload, 'orders', orderWhere, {
      tenant: t,
      user: uid,
      course: course.id,
      cohort: cohort?.id ?? null,
      subtotal: price,
      total: price,
      status: unpaid ? 'partially_paid' : 'paid',
      instalments: unpaid
        ? [
            { index: 1, amount: price / 2, dueDate: new Date(Date.now() - 30 * DAY).toISOString(), status: 'paid', paidAt: new Date(Date.now() - 30 * DAY).toISOString() },
            { index: 2, amount: price / 2, dueDate: new Date(Date.now() - 2 * DAY).toISOString(), status: 'pending' },
          ]
        : [{ index: 1, amount: price, dueDate: new Date(Date.now() - 10 * DAY).toISOString(), status: 'paid', paidAt: new Date(Date.now() - 10 * DAY).toISOString() }],
    })
    if (!unpaid) {
      await upsertBy(payload, 'enrollments', orderWhere, { tenant: t, user: uid, course: course.id, cohort: cohort?.id ?? null, status: 'active' })
    }
  }

  console.info(`Access cast ready in "${TENANT}": ${CAST.length} users (+ super admin from the seed), demo2 academy, leads and orders. Passwords: apps/web/.env (ACCESS_*_PASSWORD).`)
  process.exit(0)
}

main().catch((err: unknown) => {
  console.error(err instanceof Error ? err.message : err)
  process.exit(1)
})
